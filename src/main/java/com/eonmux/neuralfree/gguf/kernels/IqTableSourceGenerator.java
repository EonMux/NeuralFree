package com.eonmux.neuralfree.gguf.kernels;

import com.eonmux.neuralfree.gguf.quant.QuantTables;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Arrays;
import java.util.Locale;

/**
 * Generates the committed IQ grid table sources of the LLM kernels from {@link QuantTables}, the single
 * source of the table data:
 * <ul>
 *   <li>{@value #OPENCL_RELATIVE_PATH}: dual-dialect C tables in {@code NF_TABLE} form, with the names the
 *       OpenCL/CUDA I-quant decoders use ({@code KSIGNS_IQ2XS_CL}, {@code IQ2XXS_GRID_CL}, ...);</li>
 *   <li>{@value #GLSL_RELATIVE_PATH}: GLSL const grids selected by {@code QTYPE}, their shared-memory
 *       copies, {@code nf_iq_init_shared()} and the {@code nf_iq*} accessors (the layout that
 *       {@code shaders/llm/common} defines; ksigns are computed from their parity form).</li>
 * </ul>
 * {@code main} writes both files under a resources root (default {@code src/main/resources}); the
 * {@code IqTableSourcesTest} keeps the committed files equal to this output.
 */
public final class IqTableSourceGenerator {

    /** Path of the C table header relative to the resources root. */
    public static final String OPENCL_RELATIVE_PATH = "kernels/llm/common/iq_tables.h";
    /** Path of the GLSL table include relative to the resources root. */
    public static final String GLSL_RELATIVE_PATH = "shaders/llm/common/iq_tables.glsl";

    private static final String DEFAULT_RESOURCES_ROOT = "src/main/resources";
    private static final String GENERATED_NOTE =
            "generated by gguf.kernels.IqTableSourceGenerator from gguf.quant.QuantTables; do not edit";
    /** Origin and licence of the table data, the second line of the C header. */
    private static final String ATTRIBUTION_C = "/* Grid and sign tables from llama.cpp/ggml (ggml/src/ggml-common.h),"
            + " MIT License; see THIRD-PARTY-NOTICES.md. */\n";

    private static final String GLSL_PREAMBLE = ""
            + "/* common/iq_tables.glsl - IQ grid tables (generated from gguf/quant/QuantTables.java, identical to\n"
            + " * the llama.cpp grids) and their workgroup-shared copies. Requires: common/nf_common.glsl,\n"
            + " * common/quant_blocks.glsl.\n"
            + " *\n"
            + " * Grid tables from llama.cpp/ggml (ggml/src/ggml-common.h; the IQ1_S packing of\n"
            + " * ggml-vulkan/vulkan-shaders/types.glsl), MIT License; see THIRD-PARTY-NOTICES.md.\n"
            + " *\n"
            + " * Only the grid used by the selected QTYPE is declared, so the shared footprint per variant is at\n"
            + " * most 8 KB (IQ2_S). Shaders call nf_iq_init_shared() at the top of main(), from every invocation\n"
            + " * and before any return; decoders then read the grids through the nf_iq* accessors only.\n"
            + " *   IQ2_XXS / IQ2_XS / IQ2_S : uvec2 entries, 8 unsigned bytes, byte j = nf_iq_grid_byte(g, j)\n"
            + " *   IQ3_XXS / IQ3_S          : uint entries, 4 unsigned bytes\n"
            + " *   IQ1_S / IQ1_M            : 16-bit entries, coordinate j in {-1, 0, 1} = nf_iq1s_val(i, j)\n"
            + " */\n"
            + "#ifndef NF_IQ_TABLES_GLSL\n"
            + "#define NF_IQ_TABLES_GLSL\n"
            + "\n"
            + "#ifndef NF_QUANT_BLOCKS_GLSL\n"
            + "#error \"common/iq_tables.glsl requires common/quant_blocks.glsl\"\n"
            + "#endif\n"
            + "\n"
            + "/* Byte j in [0, 8) of a packed 8-byte grid entry. */\n"
            + "uint nf_iq_grid_byte(uvec2 g, uint j) {\n"
            + "    return bitfieldExtract(j < 4u ? g.x : g.y, int((j & 3u) * 8u), 8);\n"
            + "}\n"
            + "\n"
            + "/* ksigns_iq2xs[i] for i in [0, 128): the 7 sign bits plus an even-parity eighth bit\n"
            + " * (equal to the 128-entry table of llama.cpp ggml-common.h). */\n"
            + "uint nf_iq2_ksigns(uint i) {\n"
            + "    return i | ((uint(bitCount(i)) & 1u) << 7);\n"
            + "}\n"
            + "\n";

    private static final String GLSL_EPILOGUE = ""
            + "/* Copies const table src[n] into shared dst[n] with all invocations of the workgroup. */\n"
            + "#define nf_iq_copy_loop(dst, src, n) \\\n"
            + "    for (uint nf_iq_i = gl_LocalInvocationIndex; nf_iq_i < (n); nf_iq_i += NF_WG_INVOCATIONS) { \\\n"
            + "        dst[nf_iq_i] = src[nf_iq_i]; \\\n"
            + "    }\n"
            + "\n"
            + "/* Fills the shared grid of the selected QTYPE and synchronizes the workgroup; no-op for types\n"
            + " * without a grid. Call from every invocation, in uniform control flow, before any return. */\n"
            + "void nf_iq_init_shared() {\n"
            + "#ifdef NF_IQ_SHARED_COPY\n"
            + "    NF_IQ_SHARED_COPY();\n"
            + "    barrier();\n"
            + "#endif\n"
            + "}\n"
            + "\n"
            + "#endif /* NF_IQ_TABLES_GLSL */\n";

    private IqTableSourceGenerator() {
    }

    /** C table header for the tables of {@link QuantTables}. */
    public static String openCl() {
        return openCl(IqGridData.fromQuantTables());
    }

    /** GLSL table include for the tables of {@link QuantTables}. */
    public static String glsl() {
        return glsl(IqGridData.fromQuantTables());
    }

    /** C table header ({@value #OPENCL_RELATIVE_PATH}) for the given tables. */
    public static String openCl(IqGridData t) {
        StringBuilder sb = new StringBuilder(200_000);
        sb.append("/* common/iq_tables.h - IQ quant sign and grid tables (").append(GENERATED_NOTE)
          .append("). Requires: common/dialect.h */\n");
        sb.append(ATTRIBUTION_C);
        sb.append("#ifndef NF_IQ_TABLES_H\n#define NF_IQ_TABLES_H\n");

        sb.append("\n/* ksigns_iq2xs: 7-bit sign index -> 8-bit sign pattern. */\n");
        appendC(sb, "uchar", "KSIGNS_IQ2XS_CL", 16, decimalBytes(t.ksignsIq2xs()));
        sb.append("\n/* iq3xxs_grid: 256 entries of 4 unsigned bytes. */\n");
        appendC(sb, "uint", "IQ3XXS_GRID_CL", 8, hexUints(t.iq3xxsGrid()));
        sb.append("\n/* iq3s_grid: 512 entries of 4 unsigned bytes. */\n");
        appendC(sb, "uint", "IQ3S_GRID_CL", 8, hexUints(t.iq3sGrid()));
        sb.append("\n/* iq2xxs_grid: 256 entries of 8 unsigned bytes. */\n");
        appendC(sb, "nf_u64", "IQ2XXS_GRID_CL", 4, hexU64s(t.iq2xxsGrid()));
        sb.append("\n/* iq2xs_grid: 512 entries of 8 unsigned bytes. */\n");
        appendC(sb, "nf_u64", "IQ2XS_GRID_CL", 4, hexU64s(t.iq2xsGrid()));
        sb.append("\n/* iq2s_grid: 1024 entries of 8 unsigned bytes. */\n");
        appendC(sb, "nf_u64", "IQ2S_GRID_CL", 4, hexU64s(t.iq2sGrid()));
        sb.append("\n/* iq1s_grid: 2048 entries of 8 signed bytes in {-1, 0, 1}. */\n");
        appendC(sb, "nf_u64", "IQ1S_GRID_CL", 4, hexU64s(t.iq1sGrid()));

        sb.append("\n#endif /* NF_IQ_TABLES_H */\n");
        return sb.toString();
    }

    /** GLSL table include ({@value #GLSL_RELATIVE_PATH}) for the given tables. */
    public static String glsl(IqGridData t) {
        requireParityKsigns(t.ksignsIq2xs());
        StringBuilder sb = new StringBuilder(200_000);
        sb.append(GLSL_PREAMBLE);
        sb.append("#ifdef QTYPE\n\n");
        appendGlslGrid(sb, "QT_IQ2_XXS", "uvec2", "IQ2XXS", "iq2xxs", 4, uvec2s(t.iq2xxsGrid()));
        appendGlslGrid(sb, "QT_IQ2_XS", "uvec2", "IQ2XS", "iq2xs", 4, uvec2s(t.iq2xsGrid()));
        appendGlslGrid(sb, "QT_IQ2_S", "uvec2", "IQ2S", "iq2s", 4, uvec2s(t.iq2sGrid()));
        appendGlslGrid(sb, "QT_IQ3_XXS", "uint", "IQ3XXS", "iq3xxs", 8, hexUints(t.iq3xxsGrid()));
        appendGlslGrid(sb, "QT_IQ3_S", "uint", "IQ3S", "iq3s", 8, hexUints(t.iq3sGrid()));

        sb.append("#if QTYPE == QT_IQ1_S || QTYPE == QT_IQ1_M\n"
                + "/* Two 16-bit entries per word (entry 2k in the low half); coordinate j of an entry is a 2-bit\n"
                + " * two's complement field at bits 2j..2j+1 (llama.cpp types.glsl:559 iq1s_grid_const). */\n");
        appendGlslTable(sb, "uint", "IQ1S", "iq1s", 8, hexUints(packIq1s(t.iq1sGrid())));
        sb.append("/* 16-bit packed grid entry i in [0, 2048). */\n"
                + "uint nf_iq1s(uint i) {\n"
                + "    return bitfieldExtract(nf_iq1s_grid[i >> 1], int((i & 1u) * 16u), 16);\n"
                + "}\n"
                + "/* Coordinate j in [0, 8) of grid entry i: -1, 0 or 1. */\n"
                + "int nf_iq1s_val(uint i, uint j) {\n"
                + "    return bitfieldExtract(int(nf_iq1s(i)), int(2u * j), 2);\n"
                + "}\n"
                + "#endif\n\n");

        sb.append("#endif /* QTYPE */\n\n");
        sb.append(GLSL_EPILOGUE);
        return sb.toString();
    }

    /**
     * The GLSL decoders compute ksigns_iq2xs[i] as {@code i | parity(i) << 7} instead of storing it; this
     * holds for the ggml table and is enforced here so the two forms never diverge.
     */
    static void requireParityKsigns(int[] ksigns) {
        for (int i = 0; i < ksigns.length; i++) {
            int expected = i | ((Integer.bitCount(i) & 1) << 7);
            if (ksigns[i] != expected) {
                throw new IllegalArgumentException("KSIGNS_IQ2XS[" + i + "] = " + ksigns[i]
                        + " is not the parity form " + expected + " that iq_tables.glsl computes");
            }
        }
    }

    /**
     * IQ1_S grid repacked to 16 bits per entry: coordinate {@code j} (byte {@code j} of the 64-bit entry, a
     * value in {-1, 0, 1}) becomes the 2-bit two's-complement field at bits {@code 2j..2j+1}; entries
     * {@code 2k} and {@code 2k+1} share word {@code k}, low half first.
     */
    static int[] packIq1s(long[] grid) {
        if (grid.length % 2 != 0) {
            throw new IllegalArgumentException("iq1s grid length " + grid.length + " is odd");
        }
        int[] out = new int[grid.length / 2];
        for (int e = 0; e < grid.length; e++) {
            int packed = 0;
            for (int j = 0; j < 8; j++) {
                int v = (byte) (grid[e] >>> (8 * j));
                if (v < -1 || v > 1) {
                    throw new IllegalArgumentException(
                            "iq1s grid entry " + e + " coordinate " + j + " is " + v + ", outside {-1, 0, 1}");
                }
                packed |= (v & 3) << (2 * j);
            }
            out[e >> 1] |= packed << (16 * (e & 1));
        }
        return out;
    }

    /**
     * Writes both table sources under a resources root.
     *
     * @param args optional single argument: the resources root (default {@code src/main/resources})
     */
    public static void main(String[] args) {
        if (args.length > 1) {
            System.err.println("usage: IqTableSourceGenerator [resources-root]");
            System.exit(2);
        }
        Path root = Paths.get(args.length == 1 ? args[0] : DEFAULT_RESOURCES_ROOT);
        try {
            IqGridData tables = IqGridData.fromQuantTables();
            write(root.resolve(OPENCL_RELATIVE_PATH), openCl(tables));
            write(root.resolve(GLSL_RELATIVE_PATH), glsl(tables));
        } catch (IOException | RuntimeException e) {
            System.err.println("IqTableSourceGenerator failed: " + e.getMessage());
            System.exit(1);
        }
    }

    private static void write(Path path, String content) throws IOException {
        Path parent = path.toAbsolutePath().getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }
        Files.write(path, content.getBytes(StandardCharsets.UTF_8));
        System.out.println("wrote " + path.toAbsolutePath());
    }

    private static void appendC(StringBuilder sb, String type, String name, int perLine, String[] values) {
        sb.append("NF_TABLE(").append(type).append(", ").append(name).append(", ").append(values.length)
          .append(") = {\n");
        appendValues(sb, perLine, values);
        sb.append("};\n");
    }

    private static void appendGlslGrid(StringBuilder sb, String qtype, String type, String upper, String lower,
                                       int perLine, String[] values) {
        sb.append("#if QTYPE == ").append(qtype).append('\n');
        appendGlslTable(sb, type, upper, lower, perLine, values);
        sb.append(type).append(" nf_").append(lower).append("(uint i) {\n")
          .append("    return nf_").append(lower).append("_grid[i];\n")
          .append("}\n")
          .append("#endif\n\n");
    }

    private static void appendGlslTable(StringBuilder sb, String type, String upper, String lower, int perLine,
                                        String[] values) {
        int n = values.length;
        sb.append("const ").append(type).append(" NF_").append(upper).append("_GRID[").append(n).append("] = {\n");
        appendValues(sb, perLine, values);
        sb.append("};\n");
        sb.append("shared ").append(type).append(" nf_").append(lower).append("_grid[").append(n).append("];\n");
        sb.append("#define NF_IQ_SHARED_COPY() nf_iq_copy_loop(nf_").append(lower).append("_grid, NF_")
          .append(upper).append("_GRID, ").append(n).append("u)\n");
    }

    private static void appendValues(StringBuilder sb, int perLine, String[] values) {
        for (int i = 0; i < values.length; i++) {
            if (i % perLine == 0) {
                sb.append("    ");
            }
            sb.append(values[i]);
            boolean last = i == values.length - 1;
            if (!last) {
                sb.append(',');
            }
            sb.append(last || i % perLine == perLine - 1 ? "\n" : " ");
        }
    }

    private static String[] decimalBytes(int[] values) {
        String[] out = new String[values.length];
        for (int i = 0; i < values.length; i++) {
            out[i] = Integer.toString(values[i] & 0xFF);
        }
        return out;
    }

    private static String[] hexUints(int[] values) {
        String[] out = new String[values.length];
        for (int i = 0; i < values.length; i++) {
            out[i] = String.format(Locale.ROOT, "0x%08xu", values[i]);
        }
        return out;
    }

    private static String[] hexU64s(long[] values) {
        String[] out = new String[values.length];
        for (int i = 0; i < values.length; i++) {
            out[i] = String.format(Locale.ROOT, "NF_U64C(0x%016x)", values[i]);
        }
        return out;
    }

    private static String[] uvec2s(long[] values) {
        String[] out = new String[values.length];
        for (int i = 0; i < values.length; i++) {
            out[i] = String.format(Locale.ROOT, "uvec2(0x%08xu, 0x%08xu)",
                    (int) values[i], (int) (values[i] >>> 32));
        }
        return out;
    }

    /**
     * Immutable copy of the IQ sign and grid tables with their ggml lengths and value ranges validated.
     */
    public static final class IqGridData {
        /** Entries of each ggml table (llama.cpp ggml-common.h). */
        private static final int KSIGNS_IQ2XS_LEN = 128;
        private static final int IQ3XXS_GRID_LEN = 256;
        private static final int IQ3S_GRID_LEN = 512;
        private static final int IQ2XXS_GRID_LEN = 256;
        private static final int IQ2XS_GRID_LEN = 512;
        private static final int IQ2S_GRID_LEN = 1024;
        private static final int IQ1S_GRID_LEN = 2048;

        private final int[] ksignsIq2xs;
        private final int[] iq3xxsGrid;
        private final int[] iq3sGrid;
        private final long[] iq2xxsGrid;
        private final long[] iq2xsGrid;
        private final long[] iq2sGrid;
        private final long[] iq1sGrid;

        IqGridData(int[] ksignsIq2xs, int[] iq3xxsGrid, int[] iq3sGrid, long[] iq2xxsGrid,
                   long[] iq2xsGrid, long[] iq2sGrid, long[] iq1sGrid) {
            this.ksignsIq2xs = checked("KSIGNS_IQ2XS", ksignsIq2xs, KSIGNS_IQ2XS_LEN);
            this.iq3xxsGrid = checked("IQ3XXS_GRID", iq3xxsGrid, IQ3XXS_GRID_LEN);
            this.iq3sGrid = checked("IQ3S_GRID", iq3sGrid, IQ3S_GRID_LEN);
            this.iq2xxsGrid = checked("IQ2XXS_GRID", iq2xxsGrid, IQ2XXS_GRID_LEN);
            this.iq2xsGrid = checked("IQ2XS_GRID", iq2xsGrid, IQ2XS_GRID_LEN);
            this.iq2sGrid = checked("IQ2S_GRID", iq2sGrid, IQ2S_GRID_LEN);
            this.iq1sGrid = checked("IQ1S_GRID", iq1sGrid, IQ1S_GRID_LEN);
            for (int i = 0; i < this.ksignsIq2xs.length; i++) {
                if (this.ksignsIq2xs[i] < 0 || this.ksignsIq2xs[i] > 255) {
                    throw new IllegalArgumentException(
                            "KSIGNS_IQ2XS[" + i + "] = " + this.ksignsIq2xs[i] + " is not a byte value");
                }
            }
            packIq1s(this.iq1sGrid);
        }

        /** The tables of {@link QuantTables}, read through its accessors. */
        public static IqGridData fromQuantTables() {
            int[] ksigns = new int[KSIGNS_IQ2XS_LEN];
            for (int i = 0; i < ksigns.length; i++) {
                ksigns[i] = QuantTables.ksignsIq2xs(i);
            }
            int[] iq3xxs = new int[IQ3XXS_GRID_LEN];
            for (int i = 0; i < iq3xxs.length; i++) {
                iq3xxs[i] = QuantTables.iq3xxsGrid(i);
            }
            int[] iq3s = new int[IQ3S_GRID_LEN];
            for (int i = 0; i < iq3s.length; i++) {
                iq3s[i] = QuantTables.iq3sGrid(i);
            }
            long[] iq2xxs = new long[IQ2XXS_GRID_LEN];
            for (int i = 0; i < iq2xxs.length; i++) {
                iq2xxs[i] = QuantTables.iq2xxsGrid(i);
            }
            long[] iq2xs = new long[IQ2XS_GRID_LEN];
            for (int i = 0; i < iq2xs.length; i++) {
                iq2xs[i] = QuantTables.iq2xsGrid(i);
            }
            long[] iq2s = new long[IQ2S_GRID_LEN];
            for (int i = 0; i < iq2s.length; i++) {
                iq2s[i] = QuantTables.iq2sGrid(i);
            }
            long[] iq1s = new long[IQ1S_GRID_LEN];
            for (int i = 0; i < iq1s.length; i++) {
                iq1s[i] = QuantTables.iq1sGrid(i);
            }
            return new IqGridData(ksigns, iq3xxs, iq3s, iq2xxs, iq2xs, iq2s, iq1s);
        }

        public int[] ksignsIq2xs() {
            return ksignsIq2xs.clone();
        }

        public int[] iq3xxsGrid() {
            return iq3xxsGrid.clone();
        }

        public int[] iq3sGrid() {
            return iq3sGrid.clone();
        }

        public long[] iq2xxsGrid() {
            return iq2xxsGrid.clone();
        }

        public long[] iq2xsGrid() {
            return iq2xsGrid.clone();
        }

        public long[] iq2sGrid() {
            return iq2sGrid.clone();
        }

        public long[] iq1sGrid() {
            return iq1sGrid.clone();
        }

        private static int[] checked(String name, int[] values, int length) {
            if (values == null || values.length != length) {
                throw new IllegalArgumentException(name + " must have " + length + " entries, got "
                        + (values == null ? "null" : Integer.toString(values.length)));
            }
            return Arrays.copyOf(values, length);
        }

        private static long[] checked(String name, long[] values, int length) {
            if (values == null || values.length != length) {
                throw new IllegalArgumentException(name + " must have " + length + " entries, got "
                        + (values == null ? "null" : Integer.toString(values.length)));
            }
            return Arrays.copyOf(values, length);
        }
    }
}
